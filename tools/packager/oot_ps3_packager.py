"""Ship of Gadeguion Packager: builds an installable PS3 PKG from the user's own oot.o2r.

The app ships only the port's own files (EBOOT.BIN, PARAM.SFO, ICON0.PNG in payload/).
A different EBOOT.BIN can be given on the command line with --eboot (testing only).
The XMB icon is drawn from the title logo in the user's oot.o2r.
The game data comes from the oot.o2r that Ship of Harkinian generated from the user's
ROM, is checked here, and is placed in USRDIR of a PKG written on the user's own PC.
No Nintendo data is included in or distributed with this tool.
"""

import os
import struct
import sys
import threading
import zipfile

import ps3pkg
import xmb_icon

APP_TITLE = "Ship of Gadeguion Packager"
CONTENT_ID = "UP0001-OOTP30048_00-OOTPS3RUNTIMEVM0"
PORT_SOH_VERSION = (9, 2)  # the port is built from Ship of Harkinian 9.2.x
DEFAULT_PKG_NAME = "Ship of Gadeguion.pkg"

GAME_VERSIONS = {
    0xEC7011B7: ("NTSC-U 1.0", True),
    0xD43DA81F: ("NTSC-U 1.1", False),
    0x693BA2AE: ("NTSC-U 1.2", False),
    0xB044B569: ("PAL 1.0", False),
    0xB2055FBD: ("PAL 1.1", False),
    0xF7F52DB8: ("NTSC-J GameCube (Collector's Edition)", False),
    0xF611F4BA: ("NTSC-J GameCube", False),
    0xF3DD35BA: ("NTSC-U GameCube", False),
    0x09465AC3: ("PAL GameCube", False),
    0xF43B45BA: ("NTSC-J Master Quest", False),
    0xF034001A: ("NTSC-U Master Quest", False),
    0x1D4136F3: ("PAL Master Quest", False),
}

# A few resources the port needs at boot and in the first scenes.
REQUIRED_ENTRIES = [
    "scenes/shared/spot00_scene/spot00_scene",
    "scenes/shared/spot04_scene/spot04_scene",
    "scenes/shared/link_home_scene/link_home_scene",
    "audio/sequences/000_Sound_Effects",
    "audio/fonts/03_Orchestra",
]


def resource_path(name):
    base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, "payload", name)


def eboot_path(override=None):
    """The built-in EBOOT.BIN, or the file given with --eboot (testing only).
    An EBOOT.BIN that merely sits next to the program is ignored: an old one left
    in the Downloads folder silently went into players' packages (v1.1.0 .exe)."""
    return override if override else resource_path("EBOOT.BIN")


def read_versioned(data):
    """O2R metadata files start with an endianness byte (1 = big-endian)."""
    return ">" if data[:1] == b"\x01" else "<"


def game_title(o2r_path):
    """XMB title for the PKG; Master Quest archives (by the ROM checksum in oot.o2r's
    `version` file) get " MQ"."""
    title = "Ship of Gadeguion"
    try:
        with zipfile.ZipFile(o2r_path) as archive:
            data = archive.read("version")
        crc = struct.unpack(read_versioned(data) + "I", data[1:5])[0]
    except (KeyError, zipfile.BadZipFile, struct.error, OSError):
        return title
    name = GAME_VERSIONS.get(crc, ("", False))[0]
    return title + " MQ" if "Master Quest" in name else title


def set_sfo_title(sfo, title):
    """Returns PARAM.SFO with its TITLE replaced (in place, within the field's max length)."""
    sfo = bytearray(sfo)
    magic, _, key_start, data_start, count = struct.unpack_from("<4sIIII", sfo, 0)
    if magic != b"\0PSF":
        raise ValueError("PARAM.SFO: bad header")
    for i in range(count):
        key_off, _, _, max_len, data_off = struct.unpack_from("<HHIII", sfo, 20 + 16 * i)
        key = sfo[key_start + key_off:sfo.index(b"\0", key_start + key_off)]
        if key == b"TITLE":
            value = title.encode("utf-8")[:max_len - 1] + b"\0"
            start = data_start + data_off
            sfo[start:start + max_len] = value.ljust(max_len, b"\0")
            struct.pack_into("<I", sfo, 20 + 16 * i + 4, len(value))
            return bytes(sfo)
    raise ValueError("PARAM.SFO: no TITLE entry")


def check_o2r(path):
    """Returns (errors, warnings, info). Errors stop the build."""
    errors, warnings, info = [], [], []
    if not os.path.isfile(path):
        return ["File not found."], warnings, info
    try:
        archive = zipfile.ZipFile(path)
    except zipfile.BadZipFile:
        return ["This is not an O2R archive (not a valid zip file)."], warnings, info
    with archive:
        names = set(archive.namelist())
        if "version" not in names:
            if any(n.startswith("fonts/") or n.startswith("textures/ship") for n in names):
                return ["This looks like soh.o2r (Ship of Harkinian's own assets). Select oot.o2r instead - "
                        "it is next to soh.o2r in the Ship of Harkinian folder."], warnings, info
            return ["This archive has no game version information; select the oot.o2r generated by "
                    "Ship of Harkinian."], warnings, info
        version_data = archive.read("version")
        crc = struct.unpack(read_versioned(version_data) + "I", version_data[1:5])[0]
        name, tested = GAME_VERSIONS.get(crc, ("unknown version 0x%08X" % crc, False))
        info.append("Game version: %s" % name)
        if not tested:
            warnings.append("Game version %s has not been tested on the PS3 port yet "
                            "(NTSC-U 1.0 is known to work). It may have problems." % name)
        if "portVersion" in names:
            pv = archive.read("portVersion")
            major, minor, patch = struct.unpack(read_versioned(pv) + "HHH", pv[1:7])
            info.append("Made with Ship of Harkinian %d.%d.%d" % (major, minor, patch))
            if (major, minor) != PORT_SOH_VERSION:
                warnings.append("This oot.o2r was made by Ship of Harkinian %d.%d.%d; the PS3 port uses %d.%d.x. "
                                "If the game misbehaves, regenerate oot.o2r with Ship of Harkinian %d.%d.3."
                                % (major, minor, patch, PORT_SOH_VERSION[0], PORT_SOH_VERSION[1],
                                   PORT_SOH_VERSION[0], PORT_SOH_VERSION[1]))
        missing = [n for n in REQUIRED_ENTRIES if n not in names]
        if missing:
            errors.append("The archive is incomplete; missing: " + ", ".join(missing))
        info.append("%d resources" % len(names))
    return errors, warnings, info


def build(o2r_path, out_path, log, progress, eboot_override=None):
    errors, warnings, info = check_o2r(o2r_path)
    for line in info:
        log(line)
    for line in warnings:
        log("WARNING: " + line)
    if errors:
        for line in errors:
            log("ERROR: " + line)
        return False
    log("Reading files...")
    files = {}
    eboot = eboot_path(eboot_override)
    if eboot_override:
        log("Using the EBOOT given with --eboot: " + eboot)
    with open(eboot, "rb") as handle:
        files["USRDIR/EBOOT.BIN"] = handle.read()
    with open(resource_path("PARAM.SFO"), "rb") as handle:
        files["PARAM.SFO"] = handle.read()
    title = game_title(o2r_path)
    try:
        files["PARAM.SFO"] = set_sfo_title(files["PARAM.SFO"], title)
        log("XMB title: " + title)
    except (ValueError, struct.error) as error:
        log("WARNING: could not set the XMB title (%s)." % error)
    try:
        with zipfile.ZipFile(o2r_path) as archive:
            files["ICON0.PNG"] = xmb_icon.build_icon0(archive)
        log("XMB icon drawn from the title logo in your oot.o2r.")
    except (KeyError, ValueError, zipfile.BadZipFile, struct.error) as error:
        log("WARNING: could not draw the XMB icon from oot.o2r (%s); using the plain icon." % error)
        with open(resource_path("ICON0.PNG"), "rb") as handle:
            files["ICON0.PNG"] = handle.read()
    with open(o2r_path, "rb") as handle:
        files["USRDIR/oot.o2r"] = handle.read()
    log("Building the PKG (this takes a few seconds)...")
    data = ps3pkg.build_pkg(files, ["USRDIR"], CONTENT_ID,
                            progress=lambda done, total: progress(done / max(total, 1)))
    with open(out_path, "wb") as handle:
        handle.write(data)
    progress(1.0)
    log("Done: %s (%.1f MB)" % (out_path, len(data) / 1048576.0))
    log("Install it on the PS3 with Package Manager (HEN) like any other PKG.")
    return True


def run_gui():
    import tkinter as tk
    from tkinter import filedialog, messagebox, ttk

    root = tk.Tk()
    root.title(APP_TITLE)
    root.geometry("640x460")
    root.minsize(560, 400)

    frame = ttk.Frame(root, padding=14)
    frame.pack(fill="both", expand=True)

    ttk.Label(frame, text=APP_TITLE, font=("Segoe UI", 14, "bold")).pack(anchor="w")
    ttk.Label(frame, wraplength=600, justify="left",
              text="Builds an installable PS3 package of Ship of Gadeguion from your own game data. "
                   "Use the oot.o2r that Ship of Harkinian created from your ROM (it is in the Ship of "
                   "Harkinian folder). Nothing is downloaded or uploaded.").pack(anchor="w", pady=(4, 12))

    o2r_var = tk.StringVar()
    out_var = tk.StringVar(value=os.path.join(os.path.expanduser("~"), "Desktop", DEFAULT_PKG_NAME))

    def row(label, var, command):
        line = ttk.Frame(frame)
        line.pack(fill="x", pady=3)
        ttk.Label(line, text=label, width=12).pack(side="left")
        ttk.Entry(line, textvariable=var).pack(side="left", fill="x", expand=True, padx=6)
        ttk.Button(line, text="Browse...", command=command).pack(side="left")

    def pick_o2r():
        path = filedialog.askopenfilename(title="Select oot.o2r",
                                          filetypes=[("Ship of Harkinian archive", "*.o2r"), ("All files", "*.*")])
        if path:
            o2r_var.set(path)
            errors, warnings, info = check_o2r(path)
            log_clear()
            for line in info:
                log(line)
            for line in warnings:
                log("WARNING: " + line)
            for line in errors:
                log("ERROR: " + line)
            if not errors:
                log("Looks good. Press Build PKG.")

    def pick_out():
        path = filedialog.asksaveasfilename(title="Save PKG as", defaultextension=".pkg",
                                            initialfile=DEFAULT_PKG_NAME, filetypes=[("PS3 package", "*.pkg")])
        if path:
            out_var.set(path)

    row("oot.o2r", o2r_var, pick_o2r)
    row("Save PKG to", out_var, pick_out)

    bar = ttk.Progressbar(frame, mode="determinate", maximum=1.0)
    bar.pack(fill="x", pady=(12, 6))
    text = tk.Text(frame, height=12, wrap="word", state="disabled")
    text.pack(fill="both", expand=True)
    button = ttk.Button(frame, text="Build PKG")
    button.pack(pady=(10, 0))

    def log(line):
        def append():
            text.configure(state="normal")
            text.insert("end", line + "\n")
            text.see("end")
            text.configure(state="disabled")
        root.after(0, append)

    def log_clear():
        text.configure(state="normal")
        text.delete("1.0", "end")
        text.configure(state="disabled")

    def progress(value):
        root.after(0, lambda: bar.configure(value=value))

    def start():
        o2r = o2r_var.get().strip()
        out = out_var.get().strip()
        if not o2r:
            messagebox.showinfo(APP_TITLE, "Select your oot.o2r first.")
            return
        if not out:
            messagebox.showinfo(APP_TITLE, "Choose where to save the PKG.")
            return
        button.configure(state="disabled")
        log_clear()
        bar.configure(value=0)

        def work():
            try:
                ok = build(o2r, out, log, progress)
            except Exception as error:  # show any failure instead of closing silently
                log("ERROR: %s" % error)
                ok = False
            root.after(0, lambda: button.configure(state="normal"))
            if ok:
                root.after(0, lambda: messagebox.showinfo(APP_TITLE, "PKG created:\n" + out))

        threading.Thread(target=work, daemon=True).start()

    button.configure(command=start)
    root.mainloop()


def main():
    # Command line: oot_ps3_packager.py [--eboot EBOOT.BIN] <oot.o2r> <out.pkg>   (no window)
    args = sys.argv[1:]
    eboot_override = None
    if len(args) >= 2 and args[0] == "--eboot":
        eboot_override = args[1]
        args = args[2:]
    if len(args) == 2:
        ok = build(args[0], args[1], print, lambda value: None, eboot_override)
        sys.exit(0 if ok else 1)
    run_gui()


if __name__ == "__main__":
    main()
